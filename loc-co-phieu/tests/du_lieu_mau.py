def _doc(bang: str) -> list[tuple]:
    hang = []
    for dong in bang.strip().splitlines():
        ngay, o, h, l, c, v = dong.split()
        hang.append((pd.Timestamp(ngay), float(o), float(h), float(l), float(c), float(v) * 1e6))
    return hang


def _lich_su_truoc(dau: pd.Timestamp, gia_dau: float, gia_cuoi: float, so_tuan: int, kl: float,
                   seed: int) -> list[tuple]:
    """Lịch sử giả trước giai đoạn có trong ảnh: đi ngang tăng nhẹ, đủ dài để có MA250."""
    rng = np.random.default_rng(seed)
    hang = []
    gia = gia_dau
    for k in range(so_tuan):
        thu_hai = dau - pd.Timedelta(weeks=so_tuan - k)
        dich = gia_dau + (gia_cuoi - gia_dau) * (k + 1) / so_tuan
        c = max(0.5, dich * (1 + rng.normal(0, 0.02)))
        o = gia
        h = max(o, c) * (1 + abs(rng.normal(0, 0.015)))
        l = min(o, c) * (1 - abs(rng.normal(0, 0.015)))
        hang.append((thu_hai, o, h, l, c, kl * (0.7 + 0.6 * rng.random())))
        gia = c
    return hang


def tuan_sang_ngay(tuan: list[tuple]) -> pd.DataFrame:
    rows = []
    for thu_hai, o, h, l, c, v in tuan:
        ngay = [thu_hai + pd.Timedelta(days=k) for k in range(5)]
        ngay = [d for d in ngay if d.strftime("%Y-%m-%d") not in NGAY_NGHI]
        n = len(ngay)
        if n == 0:
            continue
        dong = [o + (c - o) * (k + 1) / n for k in range(n)]
        mo = [o] + dong[:-1]
        cao = [min(max(a, b) * 1.003, h) for a, b in zip(mo, dong)]
        thap = [max(min(a, b) * 0.997, l) for a, b in zip(mo, dong)]
        k_cao, k_thap = (n - 1, 0) if c >= o else (0, n - 1)
        cao[k_cao], thap[k_thap] = h, l
        for d, a, b, x, y in zip(ngay, mo, cao, thap, dong):
            rows.append((d, a, b, x, y, v / n))
    df = pd.DataFrame(rows, columns=["date", "open", "high", "low", "close", "volume"]).set_index("date")
    return df.round({"open": 3, "high": 3, "low": 3, "close": 3, "volume": 0})


def du_lieu(ma: str) -> pd.DataFrame:
    """Dữ liệu ngày mô phỏng của DRI hoặc MSR (đến hết 09/10/2026)."""
    ma = ma.upper()
    if ma == "DRI":
        tuan = _doc(DRI_TUAN)
        truoc = _lich_su_truoc(tuan[0][0], 8.2, 9.05, 40, 1.0e6, seed=1)
    elif ma == "MSR":
        tuan = _doc(MSR_TUAN)
        truoc = _lich_su_truoc(tuan[0][0], 15.5, 22.5, 70, 4.0e6, seed=2)
    else:
        raise KeyError(ma)
    return tuan_sang_ngay(truoc + tuan)


def vnindex_mau() -> pd.DataFrame:
    """VN-Index mô phỏng: tăng đều nhẹ (để bối cảnh thị trường = thuận lợi)."""
    ngay = pd.bdate_range("2025-01-02", "2026-10-09")
    ngay = ngay[~ngay.strftime("%Y-%m-%d").isin(NGAY_NGHI)]
    rng = np.random.default_rng(3)
    c = 1250 * np.cumprod(1 + 0.0006 + rng.normal(0, 0.006, len(ngay)))
    df = pd.DataFrame({"open": c / 1.001, "high": c * 1.004, "low": c * 0.995, "close": c,
                       "volume": 7e8 * (0.8 + 0.4 * rng.random(len(ngay)))}, index=ngay)
    df.index.name = "date"
    return df


